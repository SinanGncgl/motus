const CACHE = new Map<string, DictEntry | null>();

/** Look up a word in the offline starter dictionary (case-insensitive). */
export function offlineLookup(raw: string): DictEntry | null {
  const word = raw.trim().toLowerCase().replace(/[^a-z'-]/g, "");
  if (!word) return null;
  if (CACHE.has(word)) return CACHE.get(word) ?? null;
  const hit = ENTRIES[word] ?? null;
  CACHE.set(word, hit);
  return hit;
}

/** True if the word is covered by the offline starter dictionary. */
export function hasOfflineDefinition(raw: string): boolean {
  return offlineLookup(raw) !== null;
}
